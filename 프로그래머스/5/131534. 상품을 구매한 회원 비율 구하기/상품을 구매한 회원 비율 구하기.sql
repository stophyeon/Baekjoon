-- USER_INFO, ONLINE_SALE
-- 2021년 가입한 전체 회원 중 상품을 구매한 회원수, 상품을 구매한 회원의 비율을 년, 월별로 출력
-- 비율은 소수점 2번째 자리 반올림, 년,월 기준 오름차순
SELECT YEAR, MONTH ,PURCHASED_USERS, 
ROUND((PURCHASED_USERS/(SELECT COUNT(DISTINCT USER_ID) FROM USER_INFO WHERE TO_CHAR(JOINED,'YYYY') = '2021')),1) AS PUCHASED_RATIO 
FROM (
    SELECT TO_NUMBER(YEAR) AS YEAR, 
        TO_NUMBER(MONTH) AS MONTH, 
        COUNT(DISTINCT USER_ID) AS PURCHASED_USERS 
        FROM (
            SELECT B.USER_ID, TO_CHAR(A.SALES_DATE,'YYYY') AS YEAR, 
            TO_CHAR(A.SALES_DATE,'MM') AS MONTH
            FROM ONLINE_SALE A 
            JOIN USER_INFO B ON A.USER_ID = B.USER_ID
            WHERE TO_CHAR(B.JOINED,'YYYY') = '2021'
        )
    GROUP BY YEAR, MONTH
) 
ORDER BY YEAR, MONTH;